"""화면·파일에 보이는 용어를 한 곳에서 바꿉니다.

공개 전에는 '가동률'을 다른 사람에게 보이지 않게 UTIL = "ooo" 로 둡니다 (2026-11-02 사용자 요청).
공개할 때는 UTIL = "가동률" 로 한 줄만 바꾸면 앱 전체(제목·메뉴·그래프·엑셀 보고서·파일 이름)가 바뀝니다.
프로그램 안쪽에서 쓰는 열 이름("가동률")은 그대로 두고, 보여 줄 때만 w() 를 거칩니다.
"""
UTIL = "ooo"


def w(text: str) -> str:
    """보여 줄 글에서 '가동률'을 UTIL 로 바꿉니다."""
    return str(text).replace("가동률", UTIL)
