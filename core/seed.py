def compose_detail(overview: str, method: str, content: str) -> str:
    return f"· 지원개요 : {overview}\n· 인증/인정/시험법 : {method}\n· 지원내용 : {content}"


def parse_detail(text: str) -> tuple[str, str, str]:
    out = {k: "" for k in DETAIL_LABELS}
    for line in str(text or "").splitlines():
        line = line.strip().lstrip("·").strip()
        for k in DETAIL_LABELS:
            if line.startswith(k):
                out[k] = line[len(k):].lstrip(" :：").strip()
                break
    return out["지원개요"], out["인증/인정/시험법"], out["지원내용"]


