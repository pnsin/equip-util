def _range_values(ref: str) -> list[str]:
    m = re.fullmatch(r"Sheet2!\$([A-Z]+)\$(\d+)(?::\$([A-Z]+)\$(\d+))?", ref)
    col, r1, r2 = m.group(1), int(m.group(2)), int(m.group(4) or m.group(2))
    values = SHEET2_COLUMNS.get(col, [])
    return [v for v in values[r1 - 1:r2] if v]


